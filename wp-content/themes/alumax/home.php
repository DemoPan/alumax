        document.addEventListener('DOMContentLoaded', () => {
          // Category Filter Handler
          const filterButtons = document.querySelectorAll('.filter-btn');
          const articleCards = document.querySelectorAll('.article-card');

          filterButtons.forEach(btn => {
            btn.addEventListener('click', () => {
              const filter = btn.getAttribute('data-filter');

              // Reset button styles
              filterButtons.forEach(b => {
                b.classList.remove('bg-surface-container-lowest', 'font-semibold', 'text-on-surface', 'shadow-sm');
                b.classList.add('text-on-surface-variant');
              });

              // Set active state
              btn.classList.add('bg-surface-container-lowest', 'font-semibold', 'text-on-surface', 'shadow-sm');
              btn.classList.remove('text-on-surface-variant');

              // Filter card transitions
              articleCards.forEach(card => {
                const cardCat = card.getAttribute('data-category');
                if (filter === 'all' || cardCat === filter) {
                  card.style.display = 'flex';
                  setTimeout(() => {
                    card.style.opacity = '1';
                    card.style.transform = 'translateY(0)';
                  }, 20);
                } else {
                  card.style.opacity = '0';
                  card.style.transform = 'translateY(8px)';
                  setTimeout(() => {
                    card.style.display = 'none';
                  }, 200);
                }
              });
            });
          });

          // Form submission feedback
          const newsletterForm = document.getElementById('newsletter-form');
          const newsletterStatus = document.getElementById('newsletter-status');

          if (newsletterForm) {
            newsletterForm.addEventListener('submit', (e) => {
              e.preventDefault();
              const emailInput = document.getElementById('engineer-email');
              if (emailInput && emailInput.value) {
                newsletterStatus.classList.remove('hidden');
                emailInput.value = '';
                setTimeout(() => {
                  newsletterStatus.classList.add('hidden');
                }, 6000);
              }
            });
          }
        });
      </script>
