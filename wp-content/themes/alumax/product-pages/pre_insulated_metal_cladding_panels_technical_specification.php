      if (currentConfig.thick === '50mm') currentConfig.uValue = '0.42 W/m²·K';
      else if (currentConfig.thick === '75mm') currentConfig.uValue = '0.28 W/m²·K';
      else if (currentConfig.thick === '100mm') currentConfig.uValue = '0.21 W/m²·K';
      else if (currentConfig.thick === '120mm') currentConfig.uValue = '0.17 W/m²·K';
      else currentConfig.uValue = '0.14 W/m²·K';
    } else {
      if (currentConfig.thick === '50mm') currentConfig.uValue = '0.72 W/m²·K';
      else if (currentConfig.thick === '75mm') currentConfig.uValue = '0.48 W/m²·K';
      else if (currentConfig.thick === '100mm') currentConfig.uValue = '0.36 W/m²·K';
      else if (currentConfig.thick === '120mm') currentConfig.uValue = '0.30 W/m²·K';
      else currentConfig.uValue = '0.24 W/m²·K';
    }
    updateDynamicSpec();
  }

